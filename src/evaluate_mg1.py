"""MG002: evaluate MG1 against pre-registered criteria. Reads results/MG002/{main,controls}.json,
writes results/MG002/MG1_evaluation.md and results/MG002/profiles.png. No hand-entered results."""
import json, sys
import numpy as np
sys.path.insert(0, "src")
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from mg_continuum import run

T1 = {  # Pulver & LaViolette 2013, Table 1 (transcribed in spec/model_g_published.md §7)
 "amp":      {1: dict(Y=0.930, G=-0.161, X=-8.36), 2: dict(Y=1.50, G=-0.308, X=-13.6), 3: dict(Y=1.70, G=-0.411, X=-14.6)},
 "r0":       {1: dict(Y=0.724, G=0.867, X=0.642), 2: dict(Y=1.21, G=1.37, X=1.13), 3: dict(Y=1.68, G=1.85, X=1.61)},
 "rms":      {1: dict(Y=0.302, G=0.363, X=0.272), 2: dict(Y=0.665, G=0.739, X=0.634), 3: dict(Y=1.07, G=1.14, X=1.04)},
 "core_int": {1: dict(Y=0.806, G=-0.167, X=-6.59), 2: dict(Y=3.12, G=-0.710, X=-26.3), 3: dict(Y=13.2, G=-3.17, X=-111)},
 "full_int": {1: dict(Y=0.281, G=8.39e-5, X=6.01e-4), 2: dict(Y=0.893, G=2.88e-3, X=0.128), 3: dict(Y=3.30, G=2.87e-2, X=1.93)},
}
LAM = 3.08
main = json.load(open("results/MG002/main.json"))
ctl = json.load(open("results/MG002/controls.json"))
H = [0.05, 0.025, 0.0125]
def pick(n, h, t, rtol=1e-8):
    return next(r for r in main if r["n"] == n and r["h"] == h and abs(r["t"] - t) < 1e-9 and r["rtol"] == rtol)
rel = lambda a, b: (a - b) / abs(b) * 100

L = ["# MG1 evaluation (MG002)", "",
     "Generated by `src/evaluate_mg1.py` from `results/MG002/main.json` and `controls.json`.",
     "Criteria: `GATES.md` (pre-registered MG001b). Evaluated at the finest grid h = 0.0125, t = 100, rtol = 1e-8.", ""]
verdict = {}
for n in (1, 2, 3):
    r, rc = pick(n, 0.0125, 100), pick(n, 0.025, 100)
    f, fc = r["fields"], rc["fields"]
    c1 = abs(rel(r["lambda"], LAM)) <= 2
    c2 = all(abs(rel(f[k]["amp"], T1["amp"][n][k])) <= 3 for k in "GXY")
    c3 = all(abs(rel(f[k]["r0"], T1["r0"][n][k])) <= 3 for k in "GXY")
    c4 = r["max_abs_dphidt"] < 1e-4
    conv = [abs(rel(f[k][m], fc[k][m])) for k in "GXY" for m in ("amp", "r0")] + [abs(rel(r["lambda"], rc["lambda"]))]
    c5 = max(conv) < 0.5
    verdict[n] = dict(c1=c1, c2=c2, c3=c3, c4=c4, c5=c5)
    L += [f"## {n}D", "",
          "| Quantity | Field | Ours | Paper | Δ % | Crit. |", "|---|---|---|---|---|---|",
          f"| λ₀ | pooled | {r['lambda']:.4f} | 3.08 | {rel(r['lambda'], LAM):+.2f} | 1 (±2%) |"]
    for k in "GXY":
        L.append(f"| amplitude | φ_{k} | {f[k]['amp']:.4f} | {T1['amp'][n][k]} | {rel(f[k]['amp'], T1['amp'][n][k]):+.2f} | 2 (±3%) |")
    for k in "GXY":
        L.append(f"| core radius | φ_{k} | {f[k]['r0']:.4f} | {T1['r0'][n][k]} | {rel(f[k]['r0'], T1['r0'][n][k]):+.2f} | 3 (±3%) |")
    for k in "GXY":
        L.append(f"| RMS radius | φ_{k} | {f[k]['rms']:.4f} | {T1['rms'][n][k]} | {rel(f[k]['rms'], T1['rms'][n][k]):+.2f} | — |")
    for k in "GXY":
        L.append(f"| core integral | φ_{k} | {f[k]['core_int']:.4g} | {T1['core_int'][n][k]} | {rel(f[k]['core_int'], T1['core_int'][n][k]):+.2f} | — |")
    for k in "GXY":
        L.append(f"| full integral | φ_{k} | {f[k]['full_int']:.3g} | {T1['full_int'][n][k]} | — | — |")
    s300 = pick(n, 0.0125, 300)
    L += ["", f"- λ₀ per field: " + ", ".join(f"{k} {v:.4f}" for k, v in r["lambda_per_field"].items()) +
          f"; zero-spacing spread (2σ) {r['lambda_spread_2sd']:.3f}.",
          f"- Criterion 4: max |∂φ/∂t| at t = 100 = {r['max_abs_dphidt']:.2e} (threshold 1e-4). At t = 300: {s300['max_abs_dphidt']:.1e}; "
          f"φ_X(0) at t = 300 = {s300['fields']['X']['amp']:.4f}.",
          f"- Criterion 5: max change h 0.025 → 0.0125 over λ₀, amplitudes and radii = {max(conv):.3f}%.",
          f"- Tolerance check (rtol 1e-10): φ_X(0) = {pick(n, 0.0125, 100, 1e-10)['fields']['X']['amp']:.6f} vs {f['X']['amp']:.6f}.",
          f"- Minimum concentrations: " + ", ".join(f"{k} {v:.3f}" for k, v in r["min_concentration"].items()) + " (positivity holds).",
          "", "| Criterion | 1 λ₀ | 2 amp | 3 r₀ | 4 stationary | 5 grid |", "|---|---|---|---|---|---|",
          "| Result | " + " | ".join("PASS" if verdict[n][c] else "**FAIL**" for c in ("c1", "c2", "c3", "c4", "c5")) + " |", ""]

L += ["## Null controls", "", "| Dim | N1: max |φ| (no seed) | N1b: max |φ| (seed ×10⁻³) | N2 nucleation threshold (seed scale, judged t=100) |", "|---|---|---|---|"]
for n in (1, 2, 3):
    a = [x for x in ctl["N1"] if x["n"] == n]
    lo, hi = ctl["N2_threshold"][str(n)]
    L.append(f"| {n}D | {a[0]['max_abs_phi']:.1e} | {a[1]['max_abs_phi']:.1e} | {lo:.4f}–{hi:.4f} |")
L += ["", "N1 passes (< 1e-6) in all dimensions. N2: seeds at 0.25/0.5/0.75 nucleate only where above threshold; "
      "a seed at 0.99× the lower bound stays unnucleated to t = 400 in every dimension.", ""]
L += ["## Integral-balance diagnostic", "", "Measured at h = 0.025. Balance residuals are the discrete balances; these are exact up to round-off for this conservative scheme, so they measure round-off × volume.", "",
      "| Dim | R | t | I_G | I_X | I_Y | F_G | F_X | dI_G/dt | d(ΣI)/dt | res_G | res_Σ |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for d in ctl["diag"]:
    I, Fl, dI = d["I"], d["flux"], d["dIdt"]
    L.append(f"| {d['n']}D | {d['R']:.0f} | {d['t']:.0f} | {I['G']:.2e} | {I['X']:.2e} | {I['Y']:.4f} | {Fl['G']:.1e} | {Fl['X']:.1e} | "
             f"{dI['G']:.1e} | {sum(dI.values()):.1e} | {d['balance_G_residual']:.0e} | {d['balance_sum_residual']:.0e} |")
L.append("")
open("results/MG002/MG1_evaluation.md", "w").write("\n".join(L))
json.dump({str(k): v for k, v in verdict.items()}, open("results/MG002/verdict.json", "w"), indent=1)
print(json.dumps(verdict, indent=1))

# ---- figure: small multiples, one panel per field, series = dimension
C = ["#2a78d6", "#eb6834", "#1baf7a"]
fig, axs = plt.subplots(1, 3, figsize=(12, 3.6), constrained_layout=True)
for i, n in enumerate((1, 2, 3)):
    g, P, s, rhs = run(n, h=0.0125, t_end=100)
    y = s.y[:, -1]; N = g.N
    for ax, (k, sl) in zip(axs, (("G", slice(0, N)), ("X", slice(N, 2 * N)), ("Y", slice(2 * N, 3 * N)))):
        ax.plot(g.ri, y[sl], color=C[i], lw=2, label=f"{n}D")
for ax, k in zip(axs, "GXY"):
    ax.set_title(f"φ_{k}", loc="left", fontsize=11, color="#0b0b0b")
    ax.set_xlim(0, 12); ax.axhline(0, color="#c3c2b7", lw=0.8, zorder=0)
    ax.set_xlabel("r (units of L)", color="#52514e")
    for sp_ in ("top", "right"): ax.spines[sp_].set_visible(False)
    for sp_ in ("left", "bottom"): ax.spines[sp_].set_color("#c3c2b7")
    ax.tick_params(colors="#52514e")
axs[0].legend(frameon=False)
fig.suptitle("Model G stationary soliton, eq. 17 parameters, t = 100 (MG002)", x=0.01, ha="left", fontsize=12)
fig.savefig("results/MG002/profiles.png", dpi=150, facecolor="#fcfcfb")
