"""MG3 evaluation (protocol v1.3.4; GATES.md MG3 incl. the pre-run implementation specification).
Reads results/MG3/{plan.json, runs/, refs/, run_log.txt}; writes results/MG3/MG3_evaluation.md and evaluation.json.
Usage: python src/evaluate_mg3.py
"""
import os, sys, json, glob, pickle
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import mg3
from runner import reference
from stats_mg2 import welch_diff_bounds, a1_diagnostics, audit_within_cell
from lattice import euler_mean_map, P17, steady_state

OUT = os.environ.get("MG3_OUT", "results/MG3")
LINES, RES = [], {}


def P(s=""):
    LINES.append(s)


def runs_of(cell):
    return [pickle.load(open(f, "rb")) for f in sorted(glob.glob(f"{OUT}/runs/{cell}/*.pkl"), key=lambda p: int(os.path.basename(p)[:-4]))]


def fmt(v, f="{:.3e}"):
    return "—" if v is None or (isinstance(v, float) and not np.isfinite(v)) else f.format(v)


plan = json.load(open(f"{OUT}/plan.json"))
sel, screened = plan["selected"], plan["screened"]
P("# MG3 evaluation (protocol v1.3.4)\n")
P("Generated by `src/evaluate_mg3.py` from `results/MG3/`. Criteria: `GATES.md` (MG3, with A3, A4 and the pre-run implementation specification).\n")

# ---------------------------------------------------------------- Stage A
P("## Stage A (b = 29, 4 runs per Ω, T ≤ 500, early stop 50 after the first confirmed event)\n")
P("| Ω | mean dets/snapshot t<50 | excluded | runs with first event in [50,150] | post-burn-in events | startup | any confirmed |")
P("|---|---|---|---|---|---|---|")
for c in screened:
    P(f"| {c['Om']:g} | {c.get('crowd', float('nan')):.2f} | {'yes' if c['excluded'] else 'no'} | {c['count']}/4 | {c.get('n_event', '—')} | "
      f"{c.get('n_startup', '—')} | {c.get('any_event')} |")
P(f"\nMidpoints inserted: {plan['midpoints'] or 'none'}. Stage-B selection: **{sel}** ({plan['note']}).\n")
RES["stageA"] = screened; RES["selected"] = sel

# ---------------------------------------------------------------- Stage B rates
P("## Stage B: first-passage rates (b = 29; Stage-B runs only)\n")
P("| Ω | runs | events | startup | exposure | k̂ (per length·time) | 95% CI | stationary p | in C3 fit |")
P("|---|---|---|---|---|---|---|---|---|")
rates = {}
for Om in sel:
    rr = runs_of(f"B_{Om:g}")
    r = mg3.cell_rate(rr)
    r["usable"] = r["n"] >= 5 and r["stationary_ok"]
    rates[Om] = r
    P(f"| {Om:g} | {r['n_runs']} | {r['n']} | {r['n_startup']} | {r['exposure']:.0f} | {fmt(r['k'])} | "
      f"[{fmt(r['k_lo'])}, {fmt(r['k_hi'])}] | {fmt(r['stat_p'], '{:.3f}')} | {'yes' if r['usable'] else 'no'} |")
RES["rates"] = {str(k): v for k, v in rates.items()}

# ---------------------------------------------------------------- C1
P("\n## C1: spontaneous nucleation exists (≥ 10 confirmed first-nucleation events at some Ω, Stage A + B, post burn-in)\n")
per_om = {}
for c in screened:
    if not c["excluded"]:
        per_om[c["Om"]] = sum(r["event"] for r in runs_of(f"A_{c['Om']:g}"))
for Om in sel:
    per_om[Om] = per_om.get(Om, 0) + rates[Om]["n"]
for Om, n in sorted(per_om.items(), reverse=True):
    P(f"- Ω = {Om:g}: {n} events")
c1 = "PASS" if any(n >= 10 for n in per_om.values()) else "FAIL"
P(f"\n- **C1: {c1}**\n"); RES["C1"] = c1

# ---------------------------------------------------------------- C2
P("## C2: what nucleates is a Model G soliton (every Stage-B cell)\n")
ref29 = reference(29.0, 0.2)
x = ref29["x"]; win = np.abs(x) < mg3.WIN
phiX = ref29["phi"][1][win]; nrm = float(np.linalg.norm(phiX))
lam_det = mg3.wavelength_core(x, ref29["phi"][1])
c2_all, audit_projs = [], []
for Om in sel:
    rr = runs_of(f"B_{Om:g}")
    outs = {}
    for r in rr:
        for b in r["births"]:
            if not b["shared"]:
                outs[b["cls"]] = outs.get(b["cls"], 0) + 1
    tot = sum(outs.values())
    frac = outs.get("persistent", 0) / tot if tot else float("nan")
    a_ok = tot > 0 and frac >= 0.8
    nuc = [r for r in rr if r["profile"] is not None and r["profile"]["eligible"]]
    refrec = pickle.load(open(f"{OUT}/refs/R_{Om:g}.pkl", "rb")) if os.path.exists(f"{OUT}/refs/R_{Om:g}.pkl") else None
    refel = [r for r in refrec["runs"] if r.get("eligible")] if refrec else []
    # (c) wavelength of the pooled nucleated mean profile
    if nuc:
        full = np.mean([r["profile"]["full"][1] for r in nuc], axis=0)
        lam = mg3.wavelength_core(x, full)
    else:
        lam = float("nan")
    c_ok = np.isfinite(lam) and abs(lam / lam_det - 1) <= 0.05
    # (b)
    if len(nuc) >= 8 and len(refel) >= 8:
        A = np.array([r["profile"]["blocks"][:, 1, :].mean(0) for r in nuc])
        B = np.array([np.array(r["blocks"])[:, 1, :].mean(0) for r in refel])
        wb = welch_diff_bounds(A, B, nrm)
        dA = a1_diagnostics(np.array([r["profile"]["blocks"][:, 1, :] for r in nuc]), phiX)
        dB = a1_diagnostics(np.array([np.array(r["blocks"])[:, 1, :] for r in refel]), phiX)
        b_dec = ("PASS" if wb["upper"] < 0.10 else "FAIL" if wb["lower"] > 0.10 else "INCONCLUSIVE") if (dA["ok"] and dB["ok"]) else "INCONCLUSIVE (A1)"
        b_txt = f"Welch ‖Δμ‖/‖φ*_X‖ = {100*wb['diff']:.2f}% [{100*wb['lower']:.2f}, {100*wb['upper']:.2f}]%, A1 {dA['ok']}/{dB['ok']} → {b_dec}"
        for M_ in (A, B):
            mb = M_.mean(0); _, _, Vt = np.linalg.svd(M_ - mb, full_matrices=False)
            for v in Vt[:2]:
                audit_projs.append((M_ - mb) @ v)
        cell_ok = a_ok and b_dec == "PASS" and c_ok
        replaced = False
    else:
        b_dec, b_txt, replaced = "replaced", f"replaced by (a)+(c): eligible nucleated {len(nuc)}, eligible reference {len(refel)} (need ≥ 8 each)", True
        cell_ok = a_ok and c_ok
    c2_all.append(cell_ok)
    P(f"- Ω = {Om:g}: (a) persistent {outs.get('persistent', 0)} / classified {tot} = {frac:.3f} (≥ 0.8) → {'PASS' if a_ok else 'FAIL'}; "
      f"outcomes {outs}")
    P(f"  - (b) {b_txt}")
    P(f"  - (c) λ_core = {lam:.4f} vs deterministic {lam_det:.4f} ({100*(lam/lam_det-1) if np.isfinite(lam) else float('nan'):+.2f}%, ≤ 5%) → {'PASS' if c_ok else 'FAIL'}"
      f" ({len(nuc)} eligible nucleated runs of {sum(r['first'] is not None for r in rr)} with a first event)")
    P(f"  - survival to t_e + 50 (profile-eligible runs / runs with a first event): {len(nuc)}/{sum(r['first'] is not None for r in rr)}")
    RES.setdefault("C2_cells", {})[str(Om)] = dict(a=frac, a_ok=a_ok, b=b_dec, lam=lam, c_ok=bool(c_ok), n_nuc=len(nuc), n_ref=len(refel))
c2 = "PASS" if c2_all and all(c2_all) else "FAIL"
P(f"\n- **C2: {c2}**\n"); RES["C2"] = c2

# ---------------------------------------------------------------- C3
P("## C3: activated scaling (weighted fit of ln k̂ vs Ω over usable Stage-B cells)\n")
use = [(Om, rates[Om]["n"], rates[Om]["k"]) for Om in sel if rates[Om]["usable"]]
if len(use) >= 3:
    f = mg3.activated_fit(use)
    c3 = "PASS" if (f["ci"][1] < 0 and f["r2"] >= 0.9) else "FAIL"
    P(f"- cells {[u[0] for u in use]}; slope {f['slope']:.4e} (S = {f['S']:.4e}), 95% CI [{f['ci'][0]:.4e}, {f['ci'][1]:.4e}] "
      f"(t-based sensitivity [{f['ci_t'][0]:.4e}, {f['ci_t'][1]:.4e}]); weighted R² = {f['r2']:.4f}")
    RES["C3_fit"] = f
else:
    c3 = "INCONCLUSIVE"
    P(f"- usable cells (≥ 5 events, stationary): {[u[0] for u in use]} — fewer than 3")
P(f"\n- **C3: {c3}**\n"); RES["C3"] = c3

# ---------------------------------------------------------------- V5
P("## V5: rare-event τ check (middle Stage-B cell, τ/2)\n")
mid = sorted(sel, reverse=True)[len(sel) // 2] if sel else None
v5 = "NOT RUN"
if mid is not None and runs_of(f"V5_{mid:g}"):
    rh = mg3.cell_rate(runs_of(f"V5_{mid:g}")); rb = rates[mid]
    rr_ = mg3.rate_ratio(rh["n"], rh["exposure"], rb["n"], rb["exposure"])
    v5 = "PASS" if (rr_["lo"] <= 1 <= rr_["hi"] and 0.67 <= rr_["ratio"] <= 1.5) else "FAIL"
    P(f"- Ω = {mid:g}: events {rh['n']} (τ/2) vs {rb['n']} (τ); ratio {rr_['ratio']:.3f} [{rr_['lo']:.3f}, {rr_['hi']:.3f}] → **{v5}**")
P(""); RES["V5"] = v5

# ---------------------------------------------------------------- C4
P("## C4: distance from the window edge (Ω = middle Stage-B cell)\n")
c4 = "NOT RUN"
if mid is not None and runs_of(f"C4_b29.3_{mid:g}"):
    rb = {29.0: rates[mid], 29.16: mg3.cell_rate(runs_of(f"C4_b29.16_{mid:g}")), 29.3: mg3.cell_rate(runs_of(f"C4_b29.3_{mid:g}"))}
    for b, r in rb.items():
        P(f"- b = {b}: runs {r['n_runs']}, events {r['n']}, startup {r['n_startup']}, k̂ = {fmt(r['k'])} [{fmt(r['k_lo'])}, {fmt(r['k_hi'])}]")
    mono = rb[29.0]["k"] < rb[29.16]["k"] < rb[29.3]["k"]
    rr_ = mg3.rate_ratio(rb[29.3]["n"], rb[29.3]["exposure"], rb[29.0]["n"], rb[29.0]["exposure"])
    c4 = "PASS" if (mono and rr_["lo"] > 1) else "FAIL"
    P(f"- monotone point rates: {mono}; k(29.3)/k(29.0) = {rr_['ratio']:.3f}, 95% CI [{rr_['lo']:.3f}, {rr_['hi']:.3f}]")
    RES["C4_ratio"] = rr_
P(f"\n- **C4: {c4}**\n"); RES["C4"] = c4

# ---------------------------------------------------------------- controls
P("## Controls\n")
if sel:
    nOm = min(sel)
    n1 = runs_of(f"N1_b28.5_{nOm:g}")
    if n1:
        outs = {}
        for r in n1:
            for b in r["births"]:
                if not b["shared"]:
                    outs[b["cls"]] = outs.get(b["cls"], 0) + 1
        nconf = sum(r["first"] is not None for r in n1)
        nd = np.concatenate([r["n_dets"] for r in n1]).astype(float)
        P(f"- N1 (b = 28.5, Ω = {nOm:g}, {len(n1)} runs): confirmed events {nconf}; field outcomes {outs}; "
          f"detections per snapshot {nd.mean():.3f}; persistent detections per unit length·time "
          f"{sum(outs.values()) / (100.0 * sum(r['t_end'] for r in n1)):.3e}")
        RES["N1"] = dict(confirmed=nconf, outcomes=outs)
Pp = {**P17, "b": 29.0}; S0 = steady_state(Pp)
G, X, Y = (np.full(500, v) for v in S0)
G2, X2, Y2 = euler_mean_map(Pp, 0.2, 6.666666666666667e-4, 500.0, G, X, Y)
dev = max(np.max(np.abs(G2 - S0[0])), np.max(np.abs(X2 - S0[1])), np.max(np.abs(Y2 - S0[2])))
rng = np.random.default_rng(0)
G3, X3, Y3 = euler_mean_map(Pp, 0.2, 6.666666666666667e-4, 500.0, G + 1e-3 * rng.standard_normal(500), X + 1e-3 * rng.standard_normal(500), Y)
dev3 = max(np.max(np.abs(G3 - S0[0])), np.max(np.abs(X3 - S0[1])), np.max(np.abs(Y3 - S0[2])))
P(f"- N2 (Ω → ∞ mean map, b = 29, T = 500): from the exact homogeneous state max|φ| = {dev:.2e}; from a 10⁻³ random perturbation "
  f"max|φ| = {dev3:.2e} → {'PASS' if dev < 1e-6 and dev3 < 1e-3 else 'FAIL'}")
RES["N2"] = dict(exact=float(dev), perturbed=float(dev3))
if audit_projs:
    au = audit_within_cell(audit_projs)
    P(f"- Within-cell audit (C2(b) samples, A4): {au['n_tests']} tests, max |t| {au['max_stat']:.3f} vs {au['crit']:.3f}; flagged {len(au['flagged'])}")

# ---------------------------------------------------------------- verdict
P("\n## Gate verdict (as registered)\n")
budget_stop = any("[BUDGET]" in l for l in open(f"{OUT}/run_log.txt"))
if not sel:
    verdict = "FAIL" if c1 == "FAIL" else "INCONCLUSIVE"     # Stage-A terminal outcomes (a) / (e)
elif all(v == "PASS" for v in (c1, c2, c3, c4, v5)):
    verdict = "PASS"
elif c3 == "INCONCLUSIVE" or budget_stop:                  # GATES order: PASS / INCONCLUSIVE / FAIL
    verdict = "INCONCLUSIVE"
else:
    verdict = "FAIL"
P(f"**{verdict}** — C1 {c1}, C2 {c2}, C3 {c3}, C4 {c4}, V5 {v5}")
RES["verdict"] = verdict
open(f"{OUT}/MG3_evaluation.md", "w").write("\n".join(LINES) + "\n")
json.dump(RES, open(f"{OUT}/evaluation.json", "w"), indent=1, default=lambda o: o.tolist() if hasattr(o, "tolist") else str(o))
print("\n".join(LINES))
