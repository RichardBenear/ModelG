"""MG005: evaluate MG2 against the pre-registered criteria (GATES.md, protocol v1.3.3).
Reads results/MG2/cells/*.pkl; writes results/MG2/MG2_evaluation.md and evaluation.json."""
import os, sys, json, pickle
import numpy as np
from scipy import stats
sys.path.insert(0, os.path.dirname(__file__))
from runner import reference
from stats_mg2 import bias_bounds, decide, a1_diagnostics, alpha_ci, _studentized_loo
from run_mg2 import cell_decision, LADDER, B

CELLS = "results/MG2/cells"
LNA = {29.0: [15.59, 112.69, 2.73], 29.16: [15.59, 121.87, 2.84]}
L = []
def P(s=""):
    L.append(s); print(s, flush=True)

def load(name):
    p = f"{CELLS}/{name}.pkl"
    return pickle.load(open(p, "rb")) if os.path.exists(p) else None

def ladder_cell(b, Om):
    return load(f"C1_b{b}_1e8") if Om == 100000000 else load(f"L_b{b}_{Om:g}")

def win_ref(b, h=0.2):
    ref = reference(b, h); w = np.abs(ref["x"]) < 10.0
    return ref, ref["phi"][:, w]

res = {}
P("# MG2 evaluation (protocol v1.3.3)\n")
P("Generated by `src/evaluate_mg2.py` from `results/MG2/cells/`. Criteria: `GATES.md` (MG2).\n")

# ---------------------------------------------------------------- survival / eligibility overview
P("## Cells: eligibility and events\n")
P("| b | Ω | eligible / attempted | loss | replication | merge | birth |"); P("|---|---|---|---|---|---|---|")
for b in B:
    for Om in LADDER:
        c = ladder_cell(b, Om)
        if c is None:
            P(f"| {b} | {Om:g} | not run | | | | |"); continue
        ev = {k: 0 for k in ("loss", "replication", "merge", "birth")}
        for r in c["runs"]:
            for e in (r.get("events") or []):
                ev[e[0]] = ev.get(e[0], 0) + 1
        P(f"| {b} | {Om:g} | {c['n_eligible']} / {c['n_attempted']} | {ev['loss']} | {ev['replication']} | {ev['merge']} | {ev['birth']} |")
P()

# ---------------------------------------------------------------- C1, C6, N2
P("## C1 (Ω = 1e8), C6 (h = 0.1) and N2\n")
for key, name in (("C1_b29.0", "C1_b29.0_1e8"), ("C1_b29.16", "C1_b29.16_1e8"), ("C6", "C6_h0.1_b29.0_1e8")):
    c = load(name)
    if c is None:
        res[key] = "NOT RUN"; P(f"- {key}: not run"); continue
    v, det = cell_decision(c)
    res[key] = v
    P(f"- **{key}**: {v} (eligible {c['n_eligible']}/{c['n_attempted']}{', extended' if c.get('extended') else ''})")
    if isinstance(det, dict) and "G" in det:
        for nm in "GXY":
            d = det[nm]
            P(f"  - {nm}: bias point {100*d['Eb_point']:.4f}%, bounds [{100*d['lower']:.4f}, {100*d['upper']:.4f}]% "
              f"(ε 1%) → {d['decision']}; A1 {'ok' if d['a1_ok'] else 'FLAG'}")
c = load("C1_b29.0_1e8")
if c is not None:
    _, phim = win_ref(29.16)
    el = [r for r in c["runs"] if r.get("eligible")]
    R = np.array([r["blocks"] for r in el]).mean(1)
    n2 = [decide(bias_bounds(R[:, s], phim[s]), 0.01) for s in range(3)]
    res["N2"] = "PASS (control behaves: C1 fails against the wrong reference)" if "FAIL" in n2 else f"FAIL (metric did not discriminate: {n2})"
    P(f"- **N2** (b = 29 runs vs the b_mid reference): per-field decisions {n2} → {res['N2']}")
P()

# ---------------------------------------------------------------- C2
P("## C2: bias scaling α (X field, Ω ≥ 100, w = 2.0)\n")
c2 = {}
for b in B:
    oms, runs = [], []
    _, phis = win_ref(b)
    for Om in LADDER:
        if Om < 100: continue
        c = ladder_cell(b, Om)
        if c is None or c["n_eligible"] < 12: continue
        el = [r for r in c["runs"] if r.get("eligible")]
        oms.append(Om); runs.append(np.array([r["blocks"] for r in el]).mean(1)[:, 1])
    if len(oms) < 3:
        c2[b] = "INCONCLUSIVE"; P(f"- b = {b}: fewer than 3 usable cells → INCONCLUSIVE"); continue
    a, (lo, hi), fv, keep = alpha_ci({"ref": phis[1], "runs": runs}, np.array(oms, float), B=2000, widen=2.0, rng=20261028)
    if not np.isfinite(lo):
        v = "INCONCLUSIVE"
    elif 0.7 <= a <= 1.3 and not (lo <= 0.5 <= hi):
        v = "PASS"
    elif hi < 0.7 or lo > 1.3:
        v = "FAIL"
    else:
        v = "INCONCLUSIVE"
    c2[b] = v
    sel = [int(o) for o, k in zip(oms, keep) if k]
    P(f"- b = {b}: usable cells {oms}; selected (bias lower bound > 0) {sel}; α̂ = {a:.3f}, CI [{lo:.3f}, {hi:.3f}] → **{v}**")
res["C2"] = "FAIL" if "FAIL" in c2.values() else ("PASS" if all(v == "PASS" for v in c2.values()) else "INCONCLUSIVE")
P(f"- **C2: {res['C2']}**\n")

# ---------------------------------------------------------------- C3
P("## C3: far-field Ω·Var vs LNA (±10%), Ω ≥ 100, first 12 attempted runs\n")
P("| b | Ω | runs with ≥ 100 far snapshots | G | X | Y | decision |"); P("|---|---|---|---|---|---|---|")
c3 = []
for b in B:
    for Om in LADDER:
        if Om < 100: continue
        c = ladder_cell(b, Om)
        if c is None:
            c3.append("INCONCLUSIVE"); P(f"| {b} | {Om:g} | not run | | | | INCONCLUSIVE |"); continue
        first = sorted(c["runs"], key=lambda r: r["replicate"])[:12]
        ok = [r for r in first if r.get("n_far_snap", 0) >= 100]
        if len(ok) < 12:
            c3.append("INCONCLUSIVE"); P(f"| {b} | {Om:g} | {len(ok)} | | | | INCONCLUSIVE (data rule) |"); continue
        v = np.array([r["farvar"] for r in ok]).mean(0)
        dev = 100 * (v - np.array(LNA[b])) / np.array(LNA[b])
        dec = "PASS" if np.all(np.abs(dev) <= 10) else "FAIL"
        c3.append(dec)
        P(f"| {b} | {Om:g} | {len(ok)} | {v[0]:.2f} ({dev[0]:+.1f}%) | {v[1]:.2f} ({dev[1]:+.1f}%) | {v[2]:.3f} ({dev[2]:+.1f}%) | {dec} |")
res["C3"] = "FAIL" if "FAIL" in c3 else ("PASS" if all(x == "PASS" for x in c3) else "INCONCLUSIVE")
P(f"\n- **C3: {res['C3']}**\n")

# ---------------------------------------------------------------- C4
P("## C4: persistence at b_mid = 29.16, Ω ≥ 100 (no loss, replication or merge in any run)\n")
c4 = []
for Om in LADDER:
    if Om < 100: continue
    c = ladder_cell(29.16, Om)
    if c is None:
        c4.append("INCONCLUSIVE"); P(f"- Ω = {Om:g}: not run"); continue
    bad = [(r["replicate"], e) for r in c["runs"] for e in (r.get("events") or []) if e[0] in ("loss", "replication", "merge")]
    births = sum(1 for r in c["runs"] for e in (r.get("events") or []) if e[0] == "birth")
    c4.append("FAIL" if bad else "PASS")
    P(f"- Ω = {Om:g}: {len(c['runs'])} runs; violating events {len(bad)}{(' e.g. ' + str(bad[:3])) if bad else ''}; births (reported, not criteria) {births} → {'FAIL' if bad else 'PASS'}")
res["C4"] = "FAIL" if "FAIL" in c4 else ("PASS" if all(x == "PASS" for x in c4) else "INCONCLUSIVE")
P(f"\n- **C4: {res['C4']}**\n")

# ---------------------------------------------------------------- C5
P("## C5: seeded nucleation (b = 29, confirmed by the v1.3.3 field-level rule, by t = 60)\n")
c5 = []
for sc, Om, rule in ((1.5, 300, ">=0.9"), (1.5, 1000, ">=0.9"), (1.5, 3000, ">=0.9"), (0.5, 3000, "<=0.1"), (1.0, 300, "expl"), (1.0, 1000, "expl"), (1.0, 3000, "expl")):
    c = load(f"C5_s{sc}_{Om}")
    if c is None:
        if rule != "expl": c5.append("INCONCLUSIVE")
        P(f"- scale {sc}, Ω = {Om}: not run"); continue
    n = sum(r["nucleated"] for r in c["runs"]); p = n / len(c["runs"])
    cls = {k: sum(r["cls"] == k for r in c["runs"]) for k in ("persistent", "excursion", "unresolved", "none")}
    if rule == ">=0.9": d = "PASS" if p >= 0.9 else "FAIL"; c5.append(d)
    elif rule == "<=0.1": d = "PASS" if p <= 0.1 else "FAIL"; c5.append(d)
    else: d = "exploratory"
    P(f"- scale {sc}, Ω = {Om}: P(nucleate) = {n}/{len(c['runs'])} = {p:.2f} ({rule}) → {d}; classes {cls}")
res["C5"] = "FAIL" if "FAIL" in c5 else ("PASS" if c5 and all(x == "PASS" for x in c5) else "INCONCLUSIVE")
P(f"\n- **C5: {res['C5']}**\n")

# ---------------------------------------------------------------- N1
c = load("N1_b29.0_1e4")
if c is not None:
    nb = sum(len(r["births"]) for r in c["runs"])
    res["N1"] = "PASS" if nb == 0 else "FAIL"
    P(f"## N1\n\n- homogeneous start, b = 29, Ω = 1e4, 4 runs: persistent births {nb}; max detections/snapshot {[r['max_dets'] for r in c['runs']]} → **{res['N1']}**\n")

# ---------------------------------------------------------------- pooled A1 audit
P("## Gate-level pooled A1 audit (all decision-eligible cells, Bonferroni over all runs × 3 directions × 3 fields, 1%)\n")
pooled = {nm: {0: [], 1: [], 2: []} for nm in "GXY"}
for fn in sorted(os.listdir(CELLS)):
    c = pickle.load(open(f"{CELLS}/{fn}", "rb"))
    if "n_eligible" not in c or c["n_eligible"] < 12: continue
    _, phis = win_ref(c["b"], c["h"])
    el = [r for r in c["runs"] if r.get("eligible")]
    Bk = np.array([r["blocks"] for r in el])
    for s, nm in enumerate("GXY"):
        blocks = Bk[:, :, s]; M, K, d = blocks.shape
        runs = blocks.mean(1); mbar = runs.mean(0)
        W = (blocks - runs[:, None, :]).reshape(M * K, d)
        _, _, Vt = np.linalg.svd(W - W.mean(0), full_matrices=False)
        bd = mbar - phis[s]; bd = bd / np.linalg.norm(bd) if np.linalg.norm(bd) > 0 else Vt[2]
        for j, v in enumerate((bd, Vt[0], Vt[1])):
            pr = (runs - mbar) @ v
            pooled[nm][j].append((pr - pr.mean()) / pr.std(ddof=1))
audit_ok = True
ntot = sum(np.concatenate(pooled["X"][0]).size for _ in [0]) if pooled["X"][0] else 0
for nm in "GXY":
    for j in range(3):
        if not pooled[nm][j]: continue
        z = np.concatenate(pooled[nm][j])
        tcrit = stats.t.ppf(1 - 0.01 / (2 * z.size * 9), z.size - 2)
        mx = float(np.max(np.abs(_studentized_loo(z))))
        audit_ok &= mx <= tcrit
        P(f"- {nm} dir{j}: {z.size} runs, max |t| {mx:.2f} vs crit {tcrit:.2f} ({'ok' if mx <= tcrit else 'FLAG'})")
res["audit"] = "ok" if audit_ok else "FLAG"
P(f"\n- **Pooled audit: {res['audit']}**\n")

# ---------------------------------------------------------------- exploratory: particle diffusion
P("## Exploratory: particle diffusion D_p(Ω) (eligible runs; MSD at lag 5)\n")
for b in B:
    for Om in LADDER:
        c = ladder_cell(b, Om)
        if c is None or c["n_eligible"] == 0: continue
        msd = []
        for r in c["runs"]:
            if not r.get("eligible"): continue
            p = np.array(r["positions"], float)
            p = np.unwrap(p * 2 * np.pi / 100.0) * 100.0 / (2 * np.pi)
            lag = 10
            dd = p[lag:] - p[:-lag]
            dd = dd[np.isfinite(dd)]
            if dd.size: msd.append(np.mean(dd**2))
        if msd:
            D = np.mean(msd) / (2 * 5.0)
            P(f"- b = {b}, Ω = {Om:g}: D_p ≈ {D:.3e} (Ω·D_p ≈ {Om*D:.3e}), {len(msd)} runs")
P()

# ---------------------------------------------------------------- verdict
crit = [res.get(k) for k in ("C1_b29.0", "C1_b29.16", "C3", "C4", "C5", "C6")]
if any(x == "FAIL" for x in crit) or res.get("C2") == "FAIL":
    verdict = "FAIL"
elif all(x == "PASS" for x in crit) and res.get("C2") != "FAIL":
    verdict = "PASS" if res.get("audit") == "ok" else "INCONCLUSIVE (pooled audit flag; PASSes downgraded pending investigation)"
else:
    verdict = "INCONCLUSIVE"
res["verdict"] = verdict
P(f"## Gate verdict (as registered): **{verdict}**\n")
P("Criterion summary: " + ", ".join(f"{k} {res.get(k)}" for k in ("C1_b29.0", "C1_b29.16", "C2", "C3", "C4", "C5", "C6", "N1", "N2", "audit")))
open("results/MG2/MG2_evaluation.md", "w").write("\n".join(L) + "\n")
json.dump(res, open("results/MG2/evaluation.json", "w"), indent=1)
